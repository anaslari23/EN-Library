"""Deterministic metadata embedded in generated source files."""

from pathlib import Path

TOOL_VERSION = "0.2.0"


def add_provenance(source: str, source_path: str | Path, en_version: str | None, target: str) -> str:
    marker = "#" if target == "python" else "//"
    label = en_version or "legacy"
    name = Path(source_path).name
    header = (
        f"{marker} --- generated by codeinenglish {TOOL_VERSION} from {name} (en {label}) ---\n"
        f"{marker} Regenerating from {name} overwrites this file.\n"
        f"{marker} --- end generated header ---\n"
    )
    return header + source


def split_provenance(source: str) -> tuple[str, str]:
    """Return (header, code body), or ('', source) for an unmarked file."""
    lines = source.splitlines(keepends=True)
    if not lines:
        return "", source
    prefix = lines[0][:2].strip()
    begin = f"{prefix} --- generated by codeinenglish "
    end = f"{prefix} --- end generated header ---"
    if not lines[0].startswith(begin):
        return "", source
    end_index = next((index for index, line in enumerate(lines) if line.rstrip("\r\n") == end), None)
    if end_index is None:
        return "", source
    header = "".join(lines[:end_index + 1])
    body = "".join(lines[end_index + 1:])
    return header, body
